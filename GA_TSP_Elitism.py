import random
import time
import csv
import statistics
from pathlib import Path
from itertools import product

JUMLAH_PERCOBAAN = 5
JUMLAH_GENERASI = 100_000
POPULATION_SIZES = [50, 100, 200]
MUTATION_RATES = [0.01, 0.02, 0.05]
CROSSOVER_STRATEGIES = ["Single-point", "Two-point", "Order Crossover (OX)"]
ELITE_COUNT = 2
CROSSOVER_RATE = 0.90
TOURNAMENT_SIZE = 3
SEED_AWAL = 2026
INTERVAL_LOG = 1_000
OUTPUT_DIR = Path("hasil_uji_sensitivitas_ga_tsp")
OUTPUT_DIR.mkdir(exist_ok=True)

# Dataset mencakup titik 2 sampai 53; titik 1 tidak memiliki jarak input.
# Dengan demikian titik 2 menjadi titik awal dan akhir untuk semua percobaan.
NODES = sorted({n for pair in data_jarak for n in pair})
TITIK_MULAI = NODES[0]
TITIK_LAIN = [n for n in NODES if n != TITIK_MULAI]


def jarak(a, b):
    if a == b:
        return 0.0
    key = (a, b) if a < b else (b, a)
    try:
        return data_jarak[key]
    except KeyError:
        raise KeyError(f"Jarak antara titik {a} dan {b} tidak tersedia")


def hitung_total_jarak(kromosom):
    total = jarak(TITIK_MULAI, kromosom[0])
    for i in range(len(kromosom) - 1):
        total += jarak(kromosom[i], kromosom[i + 1])
    return total + jarak(kromosom[-1], TITIK_MULAI)


def buat_populasi(population_size):
    return [random.sample(TITIK_LAIN, len(TITIK_LAIN)) for _ in range(population_size)]


def seleksi_tournament(populasi, fitness, tournament_size=TOURNAMENT_SIZE):
    kandidat = random.sample(range(len(populasi)), tournament_size)
    pemenang = min(kandidat, key=lambda idx: fitness[idx])
    return populasi[pemenang][:]


def crossover_single_point(parent1, parent2):
    """Prefix parent1 dipertahankan; sisa gen diisi sesuai urutan parent2."""
    n = len(parent1)
    cut = random.randint(1, n - 1)
    child = parent1[:cut]
    child.extend(gene for gene in parent2 if gene not in child)
    return child


def crossover_two_point(parent1, parent2):
    """Segmen parent1 dipertahankan; slot kosong diisi urutan parent2."""
    n = len(parent1)
    left, right = sorted(random.sample(range(n), 2))
    child = [None] * n
    child[left:right + 1] = parent1[left:right + 1]
    genes = [gene for gene in parent2 if gene not in child]
    positions = [i for i, gene in enumerate(child) if gene is None]
    for pos, gene in zip(positions, genes):
        child[pos] = gene
    return child


def crossover_ox(parent1, parent2):
    """Order Crossover (OX): segmen dipertahankan dan sisanya mengikuti urutan parent2."""
    n = len(parent1)
    left, right = sorted(random.sample(range(n), 2))
    child = [None] * n
    child[left:right + 1] = parent1[left:right + 1]
    genes = [gene for gene in parent2 if gene not in child]
    positions = [i for i, gene in enumerate(child) if gene is None]
    for pos, gene in zip(positions, genes):
        child[pos] = gene
    return child


CROSSOVER_FUNCTIONS = {
    "Single-point": crossover_single_point,
    "Two-point": crossover_two_point,
    "Order Crossover (OX)": crossover_ox,
}


def mutasi_swap(kromosom, mutation_rate):
    if random.random() < mutation_rate:
        i, j = random.sample(range(len(kromosom)), 2)
        kromosom[i], kromosom[j] = kromosom[j], kromosom[i]
    return kromosom


def jalankan_percobaan(population_size, mutation_rate, crossover_strategy, nomor_percobaan, run_id):
    # Seed unik dan dapat direproduksi per kombinasi dan nomor percobaan
    random.seed(SEED_AWAL + run_id * 100 + nomor_percobaan)
    mulai = time.perf_counter()
    populasi = buat_populasi(population_size)
    fitness = [hitung_total_jarak(k) for k in populasi]
    idx_best = min(range(len(populasi)), key=lambda i: fitness[i])
    best_route = populasi[idx_best][:]
    best_distance = fitness[idx_best]
    generasi_best = 0
    riwayat = []
    crossover_fn = CROSSOVER_FUNCTIONS[crossover_strategy]
    jumlah_elit = min(ELITE_COUNT, population_size)

    for generasi in range(1, JUMLAH_GENERASI + 1):
        urutan = sorted(range(len(populasi)), key=lambda i: fitness[i])
        populasi_baru = [populasi[i][:] for i in urutan[:jumlah_elit]]
        while len(populasi_baru) < population_size:
            parent1 = seleksi_tournament(populasi, fitness)
            parent2 = seleksi_tournament(populasi, fitness)
            if random.random() < CROSSOVER_RATE:
                child = crossover_fn(parent1, parent2)
            else:
                child = parent1[:]
            child = mutasi_swap(child, mutation_rate)
            populasi_baru.append(child)

        populasi = populasi_baru
        fitness = [hitung_total_jarak(k) for k in populasi]
        idx_gen_best = min(range(len(populasi)), key=lambda i: fitness[i])
        if fitness[idx_gen_best] < best_distance:
            best_distance = fitness[idx_gen_best]
            best_route = populasi[idx_gen_best][:]
            generasi_best = generasi

        if generasi % INTERVAL_LOG == 0 or generasi == 1:
            riwayat.append({
                "run_id": run_id,
                "population_size": population_size,
                "mutation_rate": mutation_rate,
                "crossover_strategy": crossover_strategy,
                "percobaan": nomor_percobaan,
                "generasi": generasi,
                "best_distance_so_far": best_distance,
                "generasi_best_ditemukan": generasi_best,
            })

    waktu = time.perf_counter() - mulai
    route_full = [TITIK_MULAI] + best_route + [TITIK_MULAI]
    hasil = {
        "run_id": run_id,
        "population_size": population_size,
        "mutation_rate": mutation_rate,
        "crossover_strategy": crossover_strategy,
        "percobaan": nomor_percobaan,
        "generasi": JUMLAH_GENERASI,
        "jarak_terbaik": best_distance,
        "generasi_ditemukannya_best": generasi_best,
        "waktu_eksekusi_detik": waktu,
        "rute_terbaik": " -> ".join(map(str, route_full)),
    }
    return hasil, riwayat


def simpan_csv(filename, rows):
    if not rows:
        return
    with open(OUTPUT_DIR / filename, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


